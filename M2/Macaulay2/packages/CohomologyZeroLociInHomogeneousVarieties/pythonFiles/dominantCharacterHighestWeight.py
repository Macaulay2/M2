"""
Computation of dominant weights and their multiplicities for an irreducible
representation, via the Freudenthal multiplicity formula.

This module is called from Macaulay2 (see LieFunctions.m2 ->
dominantCharacterHighestWeight), which imports it via Python-in-M2 and calls
only dominantCharacterHighestWeight, the entry point at the bottom.
posRoots, lam, rho, simpleRoots, rootNorms, M, poincare are all built on the
M2 side (root system data, the highest weight, and precomputed Poincare
polynomials of parabolic subgroups) and passed in as plain Python lists /
dictionaries.
"""

from typing import List
import numpy as np
from fractions import Fraction

Weight = List[int]


class SmartRoot:
    """
    A positive root paired with the (few) coordinate positions where it is
    nonzero, so that dominant_weights only has to check those positions
    when testing dominance, instead of the whole weight vector.
    """
    def __init__(self, root: Weight):
        self.root = root
        self.positions = [j for j, val in enumerate(root) if val != 0]


def scalar_product(u, v, rootNorms, M):
    """
    Scalar product of two weights u, v with respect to the Cartan matrix
    inverse M and the root norms rootNorms.
    """
    u = np.array([Fraction(x) for x in u])
    v = np.array([Fraction(x) for x in v])
    root_norms = np.array([Fraction(x) for x in rootNorms])
    M_np = np.array([[Fraction(x) for x in row] for row in M])
    transformed_u = M_np.dot(u)
    products = transformed_u * v * root_norms
    return sum(products) / Fraction(2)


def plus_rho_norm(w, rho, rootNorms, M):
    """Scalar product of (w + rho) with itself."""
    w_plus_rho = [wi + ri for wi, ri in zip(w, rho)]
    return scalar_product(w_plus_rho, w_plus_rho, rootNorms, M)


def sort_layer(X, rho, rootNorms, M):
    """Sort a list of weights X by decreasing value of plus_rho_norm."""
    Y = [(plus_rho_norm(X[i], rho, rootNorms, M), i) for i in range(len(X))]
    Y.sort(reverse=True)
    return [X[i] for (_, i) in Y]


def dominant_weights(posRoots: List[Weight], l: Weight) -> List[Weight]:
    """
    Enumerate all dominant weights of the irreducible representation with
    highest weight l, by repeatedly subtracting positive roots and keeping
    only the results that stay dominant (layer by layer, starting from l).
    """
    smartRoots = [SmartRoot(r) for r in posRoots]
    nextLayer: List[Weight] = [l]
    dominantWeights = set()
    while nextLayer:
        previousLayer = nextLayer
        nextLayer = []
        for w in previousLayer:
            dominantWeights.add(tuple(w))
        for u in previousLayer:
            for sr in smartRoots:
                w = [ui - ri for ui, ri in zip(u, sr.root)]
                # only check the positions where the root is nonzero
                if all(w[j] >= 0 for j in sr.positions):
                    if tuple(w) not in dominantWeights:
                        nextLayer.append(w)
        unique_set = set(tuple(v) for v in nextLayer)
        nextLayer = [list(v) for v in sorted(unique_set)]
    return [list(v) for v in sorted(dominantWeights)]


def weight_stabilizer(X, w, simpleRoots, rootNorms, M):
    """
    Indices i in X such that the i-th simple root is orthogonal to w, i.e.
    the subset of simple reflections that fix w (the stabilizer of w in the
    Weyl group, generated by simple reflections).
    """
    e = [i for i in X if scalar_product(simpleRoots[i - 1], w, rootNorms, M) == 0]
    return set(e)


def special_orbit_representatives(posRoots, T):
    """Positive roots that are non-negative on every simple root index in T."""
    l = []
    for r in posRoots:
        skip_root = False
        for i in T:
            if r[i - 1] < 0:
                skip_root = True
                break
        if skip_root:
            continue
        l.append(r)
    return l


def is_root(P, r, M):
    """
    Whether r is a root of the parabolic subalgebra associated to P, i.e.
    its coordinates outside P (in the basis given by M) all vanish.
    """
    rank = len(r)
    C = [i - 1 for i in range(1, rank + 1) if i not in P]  # complement of P
    zero_list = [0] * len(C)
    M_np = np.array([[Fraction(x) for x in row] for row in M])
    coeffs = M_np.dot(r)
    selected = [coeffs[i] for i in C]
    return selected == zero_list


def orbit_size(T, xi, simpleRoots, rootNorms, M, poincare):
    """
    Size of the Weyl-group orbit of xi under the parabolic subgroup
    associated to T, computed as a ratio of Poincare polynomial values
    |W_T| / |W_S| (doubled when xi is not itself a root of the parabolic).
    """
    size_WmodT = poincare[tuple(sorted(T))]
    S = weight_stabilizer(T, xi, simpleRoots, rootNorms, M)
    size_WmodS = poincare[tuple(sorted(S))]
    ratio = Fraction(size_WmodS, size_WmodT)
    if is_root(T, xi, M):
        return ratio
    else:
        return 2 * ratio


def reflect(n, p, simpleRoots):
    """Apply the n-th simple reflection to the weight p (in root coordinates)."""
    p = np.array(p)
    r = np.array(simpleRoots[n - 1])
    return p - p[n - 1] * r


def dominant_conjugate(lam, simpleRoots):
    """Bring the weight lam into the dominant Weyl chamber by simple reflections."""
    v = np.array(lam)
    rank = len(lam)
    while not all(x >= 0 for x in v):
        for j in range(1, rank + 1):
            if v[j - 1] < 0:
                v = reflect(j, v, simpleRoots)
                break
    return v


def freudenthal(lam, mu, orbits, mult, rho, simpleRoots, rootNorms, M, poincare):
    """
    Freudenthal's recursive formula: multiplicity of the weight mu in the
    irreducible representation of highest weight lam, given the already
    computed multiplicities of the weights above mu (in mult).
    """
    num = 0
    for gamma_tuple, orbitSize in orbits.items():
        gamma = list(gamma_tuple)
        temp_sum = 0
        v = [mi + gi for mi, gi in zip(mu, gamma)]
        w = tuple(dominant_conjugate(v, simpleRoots))
        while w in mult:
            temp_sum += scalar_product(v, gamma, rootNorms, M) * mult[w]
            v = [vi + gi for vi, gi in zip(v, gamma)]
            w = tuple(dominant_conjugate(v, simpleRoots))
        num += orbitSize * temp_sum
    den = plus_rho_norm(lam, rho, rootNorms, M) - plus_rho_norm(mu, rho, rootNorms, M)
    result = num / den
    return int(result)


def dominantCharacterHighestWeight(posRoots, lam, rho, simpleRoots, rootNorms, M, poincare):
    """
    Main entry point, called from Macaulay2.

    Computes the multiplicity of every dominant weight in the irreducible
    representation with highest weight lam, using Freudenthal's formula.
    Orbit-size data (stabilizers and representatives) is cached per
    stabilizer subgroup, since many dominant weights share the same one.

    Returns a dictionary {weight tuple -> multiplicity} (the M2 side turns
    this into a Tally).
    """
    L = sort_layer(dominant_weights(posRoots, lam), rho, rootNorms, M)
    mult = {tuple(lam): 1}
    stabilizers = {}
    all_simple = set(range(1, len(lam) + 1))
    for nu in L[1:]:  # skip the highest weight, already set to multiplicity 1
        nu_tup = tuple(nu)
        T = weight_stabilizer(all_simple, nu, simpleRoots, rootNorms, M)
        key_T = tuple(sorted(T))
        if key_T not in stabilizers:
            x = special_orbit_representatives(posRoots, key_T)
            y = [orbit_size(key_T, xi, simpleRoots, rootNorms, M, poincare) for xi in x]
            stabilizers[key_T] = {tuple(rep): size for rep, size in zip(x, y)}
        mult[nu_tup] = freudenthal(
            lam, nu, stabilizers[key_T], mult, rho, simpleRoots, rootNorms, M, poincare
        )
    return mult
