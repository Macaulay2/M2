"""
Characters (weight multiplicities) of exterior powers Lambda^0, ..., Lambda^n
of a representation, computed inductively and memoized.

This module is called from Macaulay2 (see LieFunctions.m2 ->
multipleExteriorPowerLie), which imports it via Python-in-M2 and calls only
multipleExteriorPower, the entry point at the bottom. It is self-contained:
since each .py file is imported as an independent module from M2, this file
duplicates the same root-system helper functions found in
dominantCharacterHighestWeight.py, tensorProduct.py and exteriorPower.py,
rather than importing them.
"""

from math import floor
from typing import List
import numpy as np
from fractions import Fraction

Weight = List[int]


class SmartRoot:
    """
    A positive root paired with the (few) coordinate positions where it is
    nonzero, so that dominant_weights only has to check those positions
    when testing dominance, instead of the whole weight vector.
    """
    def __init__(self, root: Weight):
        self.root = root
        self.positions = [j for j, val in enumerate(root) if val != 0]


def scalar_product(u, v, rootNorms, M):
    """
    Scalar product of two weights u, v with respect to the Cartan matrix
    inverse M and the root norms rootNorms.
    """
    u = np.array([Fraction(x) for x in u])
    v = np.array([Fraction(x) for x in v])
    root_norms = np.array([Fraction(x) for x in rootNorms])
    M_np = np.array([[Fraction(x) for x in row] for row in M])
    transformed_u = M_np.dot(u)
    products = transformed_u * v * root_norms
    return sum(products) / Fraction(2)


def plus_rho_norm(w, rho, rootNorms, M):
    """Scalar product of (w + rho) with itself."""
    w_plus_rho = [wi + ri for wi, ri in zip(w, rho)]
    return scalar_product(w_plus_rho, w_plus_rho, rootNorms, M)


def sort_layer(X, rho, rootNorms, M):
    """Sort a list of weights X by decreasing value of plus_rho_norm."""
    Y = [(plus_rho_norm(X[i], rho, rootNorms, M), i) for i in range(len(X))]
    Y.sort(reverse=True)
    return [X[i] for (_, i) in Y]


def dominant_weights(posRoots: List[Weight], l: Weight) -> List[Weight]:
    """
    Enumerate all dominant weights of the irreducible representation with
    highest weight l, by repeatedly subtracting positive roots and keeping
    only the results that stay dominant (layer by layer, starting from l).
    """
    smartRoots = [SmartRoot(r) for r in posRoots]
    nextLayer: List[Weight] = [l]
    dominantWeights = set()
    while nextLayer:
        previousLayer = nextLayer
        nextLayer = []
        for w in previousLayer:
            dominantWeights.add(tuple(w))
        for u in previousLayer:
            for sr in smartRoots:
                w = [ui - ri for ui, ri in zip(u, sr.root)]
                # only check the positions where the root is nonzero
                if all(w[j] >= 0 for j in sr.positions):
                    if tuple(w) not in dominantWeights:
                        nextLayer.append(w)
        unique_set = set(tuple(v) for v in nextLayer)
        nextLayer = [list(v) for v in sorted(unique_set)]
    return [list(v) for v in sorted(dominantWeights)]


def weight_stabilizer(X, w, simpleRoots, rootNorms, M):
    """
    Indices i in X such that the i-th simple root is orthogonal to w, i.e.
    the subset of simple reflections that fix w (the stabilizer of w in the
    Weyl group, generated by simple reflections).
    """
    e = [i for i in X if scalar_product(simpleRoots[i - 1], w, rootNorms, M) == 0]
    return set(e)


def special_orbit_representatives(posRoots, T):
    """Positive roots that are non-negative on every simple root index in T."""
    l = []
    for r in posRoots:
        skip_root = False
        for i in T:
            if r[i - 1] < 0:
                skip_root = True
                break
        if skip_root:
            continue
        l.append(r)
    return l


def is_root(P, r, M):
    """
    Whether r is a root of the parabolic subalgebra associated to P, i.e.
    its coordinates outside P (in the basis given by M) all vanish.
    """
    rank = len(r)
    C = [i - 1 for i in range(1, rank + 1) if i not in P]  # complement of P
    zero_list = [0] * len(C)
    M_np = np.array([[Fraction(x) for x in row] for row in M])
    coeffs = M_np.dot(r)
    selected = [coeffs[i] for i in C]
    return selected == zero_list


def orbit_size(T, xi, simpleRoots, rootNorms, M, poincare):
    """
    Size of the Weyl-group orbit of xi under the parabolic subgroup
    associated to T, computed as a ratio of Poincare polynomial values
    |W_T| / |W_S| (doubled when xi is not itself a root of the parabolic).
    """
    size_WmodT = poincare[tuple(sorted(T))]
    S = weight_stabilizer(T, xi, simpleRoots, rootNorms, M)
    size_WmodS = poincare[tuple(sorted(S))]
    ratio = Fraction(size_WmodS, size_WmodT)
    if is_root(T, xi, M):
        return ratio
    else:
        return 2 * ratio


def reflect(n, p, simpleRoots):
    """Apply the n-th simple reflection to the weight p (in root coordinates)."""
    p = np.array(p)
    r = np.array(simpleRoots[n - 1])
    return p - p[n - 1] * r


def reflect_sequence(L, p, simpleRoots):
    """Apply the simple reflections listed in L to p, in reverse order."""
    q = np.array(p, dtype=int)
    for i in reversed(L):
        q = reflect(i, q, simpleRoots)
    return q


def dominant_conjugate(lam, simpleRoots):
    """
    Bring the weight lam into the dominant Weyl chamber by successive simple
    reflections.

    Returns (dominant_weight, k), where k is the number of reflections used
    (its parity gives the sign of the weight's contribution below).
    """
    v = np.array(lam)
    k = 0
    rank = len(lam)
    while not all(x >= 0 for x in v):
        for j in range(1, rank + 1):
            if v[j - 1] < 0:
                k += 1
                v = reflect(j, v, simpleRoots)
                break  # restart the outer while-loop with the new v
    return v, k


def freudenthal(lam, mu, orbits, mult, rho, simpleRoots, rootNorms, M, poincare):
    """
    Freudenthal's recursive formula: multiplicity of the weight mu in the
    irreducible representation of highest weight lam, given the already
    computed multiplicities of the weights above mu (in mult).
    """
    num = 0
    for gamma_tuple, orbitSize in orbits.items():
        gamma = list(gamma_tuple)
        temp_sum = 0
        v = [mi + gi for mi, gi in zip(mu, gamma)]
        w, k = dominant_conjugate(v, simpleRoots)
        w = tuple(w)
        while w in mult:
            temp_sum += scalar_product(v, gamma, rootNorms, M) * mult[w]
            v = [vi + gi for vi, gi in zip(v, gamma)]
            w, k = dominant_conjugate(v, simpleRoots)
            w = tuple(w)
        num += orbitSize * temp_sum
    den = plus_rho_norm(lam, rho, rootNorms, M) - plus_rho_norm(mu, rho, rootNorms, M)
    result = num / den
    return int(result)


def dominantCharacterHighestWeight(posRoots, lam, rho, simpleRoots, rootNorms, M, poincare):
    """
    Multiplicity of every dominant weight in the irreducible representation
    with highest weight lam, using Freudenthal's formula. Orbit-size data
    (stabilizers and representatives) is cached per stabilizer subgroup,
    since many dominant weights share the same one.

    Returns a dictionary {weight tuple -> multiplicity}.
    """
    L = sort_layer(dominant_weights(posRoots, lam), rho, rootNorms, M)
    mult = {tuple(lam): 1}
    stabilizers = {}
    all_simple = set(range(1, len(lam) + 1))
    for nu in L[1:]:  # skip the highest weight, already set to multiplicity 1
        nu_tup = tuple(nu)
        T = weight_stabilizer(all_simple, nu, simpleRoots, rootNorms, M)
        key_T = tuple(sorted(T))
        if key_T not in stabilizers:
            x = special_orbit_representatives(posRoots, key_T)
            y = [orbit_size(key_T, xi, simpleRoots, rootNorms, M, poincare) for xi in x]
            stabilizers[key_T] = {tuple(rep): size for rep, size in zip(x, y)}
        mult[nu_tup] = freudenthal(
            lam, nu, stabilizers[key_T], mult, rho, simpleRoots, rootNorms, M, poincare
        )
    return mult


def tensorProduct(l1, l2, simpleRoots, rho, W, tau):
    """
    Weight multiplicities of the tensor product of the irreducible
    representations with highest weights l1 and l2, given the weight table
    W of the l1-representation (each entry w: m0 meaning the weight w has
    multiplicity m0). l2 (bound to `l` below) is the highest weight for
    which the character is not yet known.

    For every weight w of W, all Weyl-group conjugates v of w are visited
    (via an explicit stack instead of recursion, mirroring Klimyk's
    algorithm), and each visited weight is "checked": w + l + rho is
    conjugated back to the dominant chamber, and if it lies strictly inside
    that chamber, its multiplicity m0 (with an alternating sign given by
    the number of reflections used) is added to the result. tau is used as
    a shortcut to check a second, related weight (tau * w) at each step.

    Returns a dictionary {weight tuple -> multiplicity}, with zero entries
    removed.
    """
    l = l2  # the highest weight whose character is being computed
    wStack = {}
    indexStack = {}
    levelStack = {}
    T = {}

    for w in list(W.keys()):
        m0 = W[w]
        sp, i, level = 1, 1, 0
        v = tuple(-x for x in w)
        v, q = dominant_conjugate(v, simpleRoots)
        maxLevel = floor(q / 2)
        maxTau = floor((q - 1) / 2)

        # push (w, i, level) onto the stack
        wStack[sp] = w
        indexStack[sp] = i
        levelStack[sp] = level
        sp += 1

        zero_weight = tuple(0 for _ in range(len(l)))
        if w == zero_weight:
            T[tuple(l)] = T.get(tuple(l), 0) + m0
            continue

        # check(w, m0): does w + l + rho land in the (open) dominant chamber?
        y = tuple(w[j] + l[j] + rho[j] for j in range(len(l)))
        y, q = dominant_conjugate(y, simpleRoots)
        if all(y[j] > 0 for j in range(len(l))):
            key = tuple(y[j] - rho[j] for j in range(len(l)))
            T[key] = T.get(key, 0) + ((-1) ** q) * m0

        # check(tau * w, m0)
        yw = reflect_sequence(tau, w, simpleRoots)
        y = tuple(yw[j] + l[j] + rho[j] for j in range(len(l)))
        y, q = dominant_conjugate(y, simpleRoots)
        if all(y[j] > 0 for j in range(len(l))):
            key = tuple(y[j] - rho[j] for j in range(len(l)))
            T[key] = T.get(key, 0) + ((-1) ** q) * m0

        # depth-first walk (via explicit stack) over the remaining Weyl
        # conjugates of w, up to distance maxLevel from w
        while sp > 1:
            sp -= 1
            w = wStack[sp]
            i = indexStack[sp]
            level = levelStack[sp]
            while i <= len(l) and level < maxLevel:
                if w[i - 1] > 0:
                    v = reflect(i, w, simpleRoots)
                    # only descend if w is a predecessor of v in this branch
                    if all(v[j - 1] >= 0 for j in range(i + 1, len(l) + 1)):
                        if i < len(l):
                            # push (w, i+1, level) to resume this branch later
                            wStack[sp] = w
                            indexStack[sp] = i + 1
                            levelStack[sp] = level
                            sp += 1
                        level += 1

                        # check(v, m0)
                        y = tuple(v[j] + l[j] + rho[j] for j in range(len(l)))
                        y, q = dominant_conjugate(y, simpleRoots)
                        if all(y[j] > 0 for j in range(len(l))):
                            key = tuple(y[j] - rho[j] for j in range(len(l)))
                            T[key] = T.get(key, 0) + ((-1) ** q) * m0

                        if level <= maxTau:
                            # check(tau * v, m0)
                            yv = reflect_sequence(tau, v, simpleRoots)
                            y = tuple(yv[j] + l[j] + rho[j] for j in range(len(l)))
                            y, q = dominant_conjugate(y, simpleRoots)
                            if all(y[j] > 0 for j in range(len(l))):
                                key = tuple(y[j] - rho[j] for j in range(len(l)))
                                T[key] = T.get(key, 0) + ((-1) ** q) * m0

                        if level >= maxLevel:
                            break
                        w, i = v, 1
                    else:
                        i += 1
                else:
                    i += 1

    return {k: v for k, v in T.items() if v != 0}  # drop zero multiplicities


def tensor_product_diz(posRoots, L1, L2, rho, simpleRoots, rootNorms, M, poincare, tau):
    """
    Tensor product of two virtual representations given as weight-
    multiplicity dictionaries L1, L2 (e.g. outputs of
    dominantCharacterHighestWeight or of a previous call to this function).

    For every pair of weights (l1 from L1, l2 from L2), the character of
    the irreducible representation with highest weight l1 is computed and
    combined with l2 via tensorProduct; all contributions are summed,
    weighted by mult1 * mult2.
    """
    T = {}
    for l1, mult1 in L1.items():
        for l2, mult2 in L2.items():
            # NB: could be optimized by choosing the "better" of l1, l2 here
            W = dominantCharacterHighestWeight(posRoots, l1, rho, simpleRoots, rootNorms, M, poincare)
            Ttemp = tensorProduct(l1, l2, simpleRoots, rho, W, tau)
            for l, coeff in Ttemp.items():
                T[l] = T.get(l, 0) + coeff * mult1 * mult2
    return {k: v for k, v in T.items() if v != 0}


def virtual_decomposition(l, m, simpleRoots, tau):
    """
    Rewrite a (possibly non-dominant, possibly singular) weight l with
    multiplicity m as a signed sum of dominant weights.

    Walks the reduced word tau of the longest Weyl group element: at each
    simple reflection k, if the current weight lies exactly on the wall
    (coordinate -1) its contribution vanishes; if it lies strictly beyond
    the wall (coordinate <= -2) it is reflected back and its sign flipped.
    This is the building block used by adamsOp to reduce n*w (which need
    not be dominant even when w is) back to a combination of dominant
    weights.

    Returns a dictionary {weight tuple -> signed multiplicity}.
    """
    sp, i, level = 1, 1, 0
    wStack, indexStack, levelStack = {}, {}, {}
    T = {}

    v_init = tuple(-x for x in l)
    _, q = dominant_conjugate(v_init, simpleRoots)
    maxLevel = floor(q / 2)
    maxTau = floor((q - 1) / 2)

    # push (l, i, level) onto the stack
    wStack[sp] = l
    indexStack[sp] = i
    levelStack[sp] = level
    sp += 1

    def straighten(y, n):
        """
        Add n copies of weight y to T, then walk it along tau, cancelling
        it (and flipping the running sign) each time a wall is crossed,
        until it settles on a dominant weight or vanishes.
        """
        y = tuple(y)
        T[y] = n
        for k in tau:
            if y[k - 1] == -1:
                T.pop(y, None)
                return
            elif y[k - 1] <= -2:
                T.pop(y, None)
                y_arr = np.array(y)
                r = np.array(simpleRoots[k - 1])
                y = tuple(y_arr - (y_arr[k - 1] + 1) * r)
                T[y] = T.get(y, 0) - n
                n = -n

    # main weight: y = l
    straighten(l, m)
    # case y = tau * l
    straighten(reflect_sequence(tau, l, simpleRoots), m)

    # other weights in the orbit (DFS with an explicit stack)
    while sp > 1:
        sp -= 1
        l_curr = wStack.get(sp, l)
        i = indexStack.get(sp, 1)
        level = levelStack.get(sp, 0)
        while i <= len(l) and level < maxLevel:
            if l_curr[i - 1] > 0:
                v = reflect(i, l_curr, simpleRoots)
                # only descend if l_curr is a predecessor of v in this branch
                if all(v[j - 1] >= 0 for j in range(i + 1, len(l) + 1)):
                    if i < len(l):
                        wStack[sp] = l_curr
                        indexStack[sp] = i + 1
                        levelStack[sp] = level
                        sp += 1
                    level += 1

                    straighten(v, m)
                    if level <= maxTau:
                        straighten(reflect_sequence(tau, v, simpleRoots), m)

                    if level >= maxLevel:
                        break
                    l_curr, i = v, 1
                else:
                    i += 1
            else:
                i += 1

    return {k: c for k, c in T.items() if c != 0}


def adamsOp(W, n, simpleRoots, tau):
    """
    n-th Adams operation on the virtual representation given by the weight
    dictionary W: replaces every weight w (with multiplicity mult) by n*w,
    then reduces n*w back to a signed sum of dominant weights via
    virtual_decomposition, and accumulates all contributions.
    """
    S = {}
    for w, mult in W.items():
        w_times_n = tuple(n * x for x in w)
        T = virtual_decomposition(w_times_n, mult, simpleRoots, tau)
        for t, coeff in T.items():
            S[t] = S.get(t, 0) + coeff
    return {k: v for k, v in S.items() if v != 0}


def exteriorPower(n, l, memory_ext, memory_adams, posRoots, rho, simpleRoots, rootNorms, M, poincare, tau, irr):
    """
    Helper for multipleExteriorPower: weight multiplicities of Lambda^n(V),
    given the already computed Lambda^0..Lambda^(n-1) (memory_ext) and Adams
    operations psi^0..psi^n (memory_adams) of the representation V, via the
    Newton recursion

        n * Lambda^n(V) = sum_{k=1}^{n} (-1)^(k-1) Lambda^(n-k)(V) (x) psi^k(V).

    irr is accepted for a uniform call signature but does not affect this
    computation: only multipleExteriorPower needs to distinguish the
    single-weight (irr=True) and list-of-weights (irr=False) cases, since
    that is where memory_ext / memory_adams are built differently.
    """
    if n == 0:
        zero_weight = tuple(0 for _ in range(len(l)))
        return {zero_weight: 1}
    elif n == 1:
        return {tuple(l): 1}
    else:
        S = {}
        for k in range(1, n + 1):
            term1 = memory_ext[n - k]
            term2 = memory_adams[k]
            T = tensor_product_diz(posRoots, term1, term2, rho, simpleRoots, rootNorms, M, poincare, tau)
            sign = (-1) ** (k - 1)
            for t, coeff in T.items():
                t = tuple(t)
                S[t] = S.get(t, 0) + sign * coeff
        # divide by n (guaranteed to be exact by the recursion)
        return {s: val // n for s, val in S.items() if val != 0}


def multipleExteriorPower(n, l, posRoots, rho, simpleRoots, rootNorms, M, poincare, tau, irr):
    """
    Main entry point, called from Macaulay2.

    Computes the characters of Lambda^0(V), ..., Lambda^n(V) for a
    representation V, in two modes selected by irr:

    - irr = True: V is the irreducible representation with highest weight
      l. Its full character W and all Adams operations psi^0..psi^n(W) are
      computed once, then exteriorPower fills memory_ext inductively.
      Returns the list [Lambda^0(V), ..., Lambda^n(V)].

    - irr = False: l is instead a list L of (weight, multiplicity) pairs
      describing a (not necessarily irreducible) virtual representation.
      Each weight's own exterior powers are computed independently and
      collected in a dictionary keyed by weight.
      Returns {weight tuple -> [Lambda^0, ..., Lambda^n] for that weight}.
    """
    if irr:
        W = dominantCharacterHighestWeight(posRoots, l, rho, simpleRoots, rootNorms, M, poincare)
        memory_adams = [adamsOp(W, i, simpleRoots, tau) for i in range(0, n + 1)]
        zero_weight = tuple(0 for _ in range(len(l)))
        memory_ext = [{zero_weight: 1}, {tuple(l): 1}]
        for i in range(2, n + 1):
            memory_ext.append(
                exteriorPower(i, l, memory_ext, memory_adams, posRoots, rho, simpleRoots, rootNorms, M, poincare, tau, irr)
            )
        return memory_ext
    else:
        # l is here a list of (weight, multiplicity) pairs
        L = l
        memory_char = {}
        memory_adams = {}
        memory_ext = {}
        zero_weight = tuple(0 for _ in range(len(L[0][0])))
        for l, m in L:  # shadows the outer l on purpose: L holds the real weights
            W = dominantCharacterHighestWeight(posRoots, l, rho, simpleRoots, rootNorms, M, poincare)
            memory_char[tuple(l)] = W
            memory_adams[tuple(l)] = [adamsOp(W, i, simpleRoots, tau) for i in range(0, n + 1)]
            memory_ext[tuple(l)] = [{zero_weight: 1}, {tuple(l): 1}]
            for i in range(2, n + 1):
                memory_ext[tuple(l)].append(
                    exteriorPower(
                        i, l, memory_ext[tuple(l)], memory_adams[tuple(l)],
                        posRoots, rho, simpleRoots, rootNorms, M, poincare, tau, irr,
                    )
                )
        return memory_ext
